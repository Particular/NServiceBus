namespace NServiceBus.Core.Analyzer.Tests.Contributors;

using System.Threading.Tasks;
using Microsoft.CodeAnalysis;
using NUnit.Framework;
using Particular.AnalyzerTesting;

[TestFixture]
public class HandlerRegistryAvailabilityAnalyzerTests
{
    const string CallsWithoutMarkup = """
                                      using NServiceBus;

                                      public class Test
                                      {
                                          public void Configure(EndpointConfiguration cfg) => cfg.Handlers.AddAll();
                                      }
                                      """;

    [Test]
    public Task ReportsEachCallWhenNoRegistryExists()
    {
        var source = """
                     using NServiceBus;

                     public class Test
                     {
                         public void Configure(EndpointConfiguration cfg)
                         {
                             [|cfg.Handlers.AddAll()|];
                             [|cfg.Handlers.AddAllSagas()|];
                             cfg?[|.Handlers.AddAllHandlers()|];
                         }
                     }
                     """;

        return Run(source).AssertDiagnostics(DiagnosticIds.NoHandlerRegistryFound);
    }

    [Test]
    public Task DoesNotReportWithoutCalls()
    {
        var source = """
                     using NServiceBus;

                     public class Test
                     {
                         public void Configure(EndpointConfiguration cfg) { }
                     }
                     """;

        return Run(source).AssertDiagnostics();
    }

    [Test]
    public Task DoesNotReportCopycatCalls()
    {
        var source = """
                     public class Test
                     {
                         public void Configure(Other other) => other.AddAll();
                     }

                     public class Other
                     {
                         public void AddAll() { }
                     }
                     """;

        return Run(source).AssertDiagnostics();
    }

    [Test]
    public Task DoesNotReportWhenTheAssemblyHasAHandler()
    {
        var source = $$"""
                       using System.Threading.Tasks;
                       using NServiceBus;

                       {{CallsWithoutMarkup.Replace("using NServiceBus;", "")}}

                       [Handler]
                       public class MyHandler : IHandleMessages<MyMessage>
                       {
                           public Task Handle(MyMessage message, IMessageHandlerContext context) => Task.CompletedTask;
                       }

                       public class MyMessage : IMessage { }
                       """;

        return Run(source).AssertDiagnostics();
    }

    [Test]
    public Task DoesNotReportWhenTheAssemblyHasASaga()
    {
        var source = $$"""
                       using System.Threading.Tasks;
                       using NServiceBus;

                       {{CallsWithoutMarkup.Replace("using NServiceBus;", "")}}

                       [Saga]
                       public class MyPolicy : Saga<MyPolicyData>, IAmStartedByMessages<MyMessage>
                       {
                           protected override void ConfigureHowToFindSaga(SagaPropertyMapper<MyPolicyData> mapper) =>
                               mapper.MapSaga(s => s.Id).ToMessage<MyMessage>(m => m.Id);

                           public Task Handle(MyMessage message, IMessageHandlerContext context) => Task.CompletedTask;
                       }

                       public class MyPolicyData : ContainSagaData
                       {
                           public string Id { get; set; }
                       }

                       public class MyMessage : IMessage
                       {
                           public string Id { get; set; }
                       }
                       """;

        return Run(source).AssertDiagnostics();
    }

    [Test]
    public Task DoesNotReportWhenTheAssemblyHasAContributorInGeneratedCode()
    {
        return Run(CallsWithoutMarkup)
            .WithSource("""
                        // <auto-generated/>
                        using NServiceBus;

                        namespace Acme
                        {
                            [HandlerRegistryContributor]
                            internal sealed class WorkflowContributor : IHandlerRegistryContributor<WorkflowContributor>
                            {
                                public static WorkflowContributor Instance { get; } = new();

                                public void AddHandlers(EndpointConfiguration configuration) { }
                                public void AddSagas(EndpointConfiguration configuration) { }
                            }
                        }
                        """, "Contributor.g.cs")
            .AssertDiagnostics();
    }

    [Test]
    public Task ReportsWhenTheOnlyContributorIsInvalid()
    {
        var source = """
                     using NServiceBus;

                     public class Test
                     {
                         public void Configure(EndpointConfiguration cfg) => [|cfg.Handlers.AddAll()|];
                     }

                     [HandlerRegistryContributor]
                     public class NotAContributor { }
                     """;

        return Run(source).AssertDiagnostics(DiagnosticIds.NoHandlerRegistryFound);
    }

    [Test]
    public Task DoesNotReportWhenAReferencedAssemblyHasARegistry()
    {
        var library = GeneratedCompilation.BuildLibrary("AcmeLibrary", """
                                                                       using System.Threading.Tasks;
                                                                       using NServiceBus;

                                                                       [Handler]
                                                                       public class LibraryHandler : IHandleMessages<LibraryMessage>
                                                                       {
                                                                           public Task Handle(LibraryMessage message, IMessageHandlerContext context) => Task.CompletedTask;
                                                                       }

                                                                       public class LibraryMessage : IMessage { }
                                                                       """);

        return Run(CallsWithoutMarkup)
            .AddReferences(MetadataReference.CreateFromImage(library))
            .AssertDiagnostics();
    }

    [Test]
    public Task ReportsWhenReferencedAssembliesHaveNoRegistry()
    {
        var plain = GeneratedCompilation.BuildLibrary("PlainLibrary", "public class Plain { }");

        var source = """
                     using NServiceBus;

                     public class Test
                     {
                         public void Configure(EndpointConfiguration cfg) => [|cfg.Handlers.AddAll()|];
                     }
                     """;

        return Run(source)
            .AddReferences(MetadataReference.CreateFromImage(plain))
            .AssertDiagnostics(DiagnosticIds.NoHandlerRegistryFound);
    }

    [Test]
    public Task DoesNotReportWhenAnInternalRegistryOfAReferencedAssemblyIsAccessible()
    {
        var library = GeneratedCompilation.BuildLibrary("AcmeInternalLibrary", InternalRegistryLibrary("Host"));

        return Run(CallsWithoutMarkup, outputAssemblyName: "Host")
            .AddReferences(MetadataReference.CreateFromImage(library))
            .AssertDiagnostics();
    }

    [Test]
    public Task ReportsWhenTheOnlyReferencedRegistryIsInaccessible()
    {
        var library = GeneratedCompilation.BuildLibrary("AcmeClosedLibrary", InternalRegistryLibrary("SomeoneElse"));

        var source = """
                     using NServiceBus;

                     public class Test
                     {
                         public void Configure(EndpointConfiguration cfg) => [|cfg.Handlers.AddAll()|];
                     }
                     """;

        return Run(source)
            .AddReferences(MetadataReference.CreateFromImage(library))
            .AssertDiagnostics(DiagnosticIds.NoHandlerRegistryFound);
    }

    static string InternalRegistryLibrary(string friendAssembly) => $$"""
                                                                     using System.Runtime.CompilerServices;
                                                                     using System.Threading.Tasks;
                                                                     using NServiceBus;

                                                                     [assembly: InternalsVisibleTo("{{friendAssembly}}")]

                                                                     [HandlerRegistryExtensions(EntryPointName = "Internal")]
                                                                     internal static partial class InternalRegistrations
                                                                     {
                                                                     }

                                                                     [Handler]
                                                                     public class LibraryHandler : IHandleMessages<LibraryMessage>
                                                                     {
                                                                         public Task Handle(LibraryMessage message, IMessageHandlerContext context) => Task.CompletedTask;
                                                                     }

                                                                     public class LibraryMessage : IMessage { }
                                                                     """;

    [Test]
    public Task ReportsWhenTheAssemblyHasAHandlerButOptsOutAndNoReferencedRegistryExists()
    {
        var source = $$"""
                       using System.Threading.Tasks;
                       using NServiceBus;

                       public class Test
                       {
                           public void Configure(EndpointConfiguration cfg) => [|cfg.Handlers.AddAll()|];
                       }

                       [Handler]
                       public class MyHandler : IHandleMessages<MyMessage>
                       {
                           public Task Handle(MyMessage message, IMessageHandlerContext context) => Task.CompletedTask;
                       }

                       public class MyMessage : IMessage { }
                       """;

        return Run(source)
            .WithProperty("build_property.NServiceBusHandlerRegistryComposition", "false")
            .AssertDiagnostics(DiagnosticIds.NoHandlerRegistryFound);
    }

    [Test]
    public Task DoesNotReportWhenTheAssemblyOptsOutButAReferencedAssemblyHasARegistry()
    {
        var library = GeneratedCompilation.BuildLibrary("AcmeLibrary", """
                                                                       using System.Threading.Tasks;
                                                                       using NServiceBus;

                                                                       [Handler]
                                                                       public class LibraryHandler : IHandleMessages<LibraryMessage>
                                                                       {
                                                                           public Task Handle(LibraryMessage message, IMessageHandlerContext context) => Task.CompletedTask;
                                                                       }

                                                                       public class LibraryMessage : IMessage { }
                                                                       """);

        return Run(CallsWithoutMarkup)
            .WithProperty("build_property.NServiceBusHandlerRegistryComposition", "false")
            .AddReferences(MetadataReference.CreateFromImage(library))
            .AssertDiagnostics();
    }

    [Test]
    public Task ReportsWhenTheOnlyReferencedRegistryOptedOut()
    {
        var library = GeneratedCompilation.BuildLibrary("AcmeOptedOutLibrary", """
                                                                               using System.Threading.Tasks;
                                                                               using NServiceBus;

                                                                               [Handler]
                                                                               public class LibraryHandler : IHandleMessages<LibraryMessage>
                                                                               {
                                                                                   public Task Handle(LibraryMessage message, IMessageHandlerContext context) => Task.CompletedTask;
                                                                               }

                                                                               public class LibraryMessage : IMessage { }
                                                                               """, GeneratedCompilation.OptOutOfComposition);

        var source = """
                     using NServiceBus;

                     public class Test
                     {
                         public void Configure(EndpointConfiguration cfg) => [|cfg.Handlers.AddAll()|];
                     }
                     """;

        return Run(source)
            .AddReferences(MetadataReference.CreateFromImage(library))
            .AssertDiagnostics(DiagnosticIds.NoHandlerRegistryFound);
    }

    [Test]
    public Task DoesNotReportCallsInGeneratedCode()
    {
        var source = """
                     // <auto-generated/>
                     using NServiceBus;

                     public class Test
                     {
                         public void Configure(EndpointConfiguration cfg) => cfg.Handlers.AddAll();
                     }
                     """;

        return Run(source).AssertDiagnostics();
    }

    static AnalyzerTest Run(string source, string outputAssemblyName = null) => AnalyzerTest.ForAnalyzer<HandlerRegistryAvailabilityAnalyzer>(outputAssemblyName).WithSource(source, "Test.cs");
}
